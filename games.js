/** Games in a given format ("all" for everything), in catalogue order. */
export function gamesByFormat(format) {
  return format === "all" ? GAMES : GAMES.filter((g) => g.format === format);
}

/** Catalogue lookup by slug. */
export const GAME_BY_SLUG = Object.fromEntries(GAMES.map((g) => [g.slug, g]));
